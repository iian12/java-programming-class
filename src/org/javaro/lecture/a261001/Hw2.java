package org.javaro.lecture.a261001;

public class Hw2 {
    public static void main(String[] args) {
        boolean flag;
        flag = (3 > 3);
        System.out.println("3>3 불리언 변수 flag=" + flag);
        flag = (4 < 3);
        System.out.println("4<3 불리언 변수 flag=" + flag);
        flag = (4 >= 3);
        System.out.println("4>=3 불리언 변수 flag=" + flag);
        flag = (3 < 3);
        System.out.println("3<3 불리언 변수 flag=" + flag);
        flag = (4 == 3);
        System.out.println("4==3 불리언 변수 flag=" + flag);
        flag = (4 != 3);
        System.out.println("4!=3 불리언 변수 flag=" + flag);
    }
}
